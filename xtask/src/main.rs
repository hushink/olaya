//! Internal validation and release-artifact tasks.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

fn usage() -> ! {
    eprintln!(
        "usage: cargo run -p xtask -- <command>\n\
         \n\
         commands:\n\
           check                 fmt, clippy, workspace tests, SDK all-features, all-families, CLI\n\
           sync-registry [--output PATH]\n\
                                 build registry-catalog.json from registry/\n\
                                 (default: target/registry-catalog.json)\n\
           sync-embedded-registry\n\
                                 regenerate crates/olaya-cli/src/registry_seed.rs\n\
           check-embedded-registry\n\
                                 verify the embedded registry seed is current"
    );
    std::process::exit(2)
}

fn cargo(args: &[&str]) -> Result<()> {
    let status = Command::new(env!("CARGO"))
        .args(args)
        .status()
        .with_context(|| format!("running cargo {}", args.join(" ")))?;
    if !status.success() {
        bail!("cargo {} failed with {status}", args.join(" "));
    }
    Ok(())
}

fn check() -> Result<()> {
    cargo(&["fmt", "--all", "--", "--check"])?;
    cargo(&[
        "clippy",
        "--workspace",
        "--all-targets",
        "--",
        "-D",
        "warnings",
    ])?;
    cargo(&["test", "--workspace"])?;
    cargo(&["test", "-p", "olaya-sdk", "--all-features"])?;
    cargo(&[
        "clippy",
        "-p",
        "olaya-sdk",
        "--all-features",
        "--all-targets",
        "--",
        "-D",
        "warnings",
    ])?;
    cargo(&[
        "test",
        "-p",
        "olaya",
        "--features",
        "serve",
        "--test",
        "serve_contract",
    ])?;
    cargo(&["check", "-p", "olaya", "--features", "all-families"])?;
    cargo(&["check", "-p", "olaya-cli"])?;
    // The bundle is a release artifact; generating it here catches registry
    // edits that cannot form a valid catalog before the release workflow runs.
    sync_registry(None)?;
    sync_embedded_registry(true)?;
    Ok(())
}

fn collect_manifests(dir: &Path, output: &mut Vec<PathBuf>) -> Result<()> {
    for entry in std::fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.is_dir() {
            collect_manifests(&path, output)?;
        } else if path
            .extension()
            .is_some_and(|extension| extension == "json")
        {
            output.push(path);
        }
    }
    Ok(())
}

fn sync_registry(output: Option<&Path>) -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("workspace root")?;
    let registry = root.join("registry");
    let mut files = Vec::new();
    collect_manifests(&registry, &mut files)?;
    files.sort();
    if files.is_empty() {
        bail!("no manifests found under {}", registry.display());
    }

    let mut manifests = Vec::with_capacity(files.len());
    for file in &files {
        let text =
            std::fs::read_to_string(file).with_context(|| format!("reading {}", file.display()))?;
        let manifest: olaya_core::RepoManifest =
            serde_json::from_str(&text).with_context(|| format!("parsing {}", file.display()))?;
        manifest
            .validate()
            .with_context(|| format!("validating {}", file.display()))?;
        manifests.push(manifest);
    }
    let bundle = olaya_core::CatalogBundle::new(manifests);
    bundle.validate().context("validating the catalog bundle")?;
    let mut text = serde_json::to_string_pretty(&bundle).context("serializing catalog")?;
    text.push('\n');

    // The bundle is a release artifact, not a checked-in source file. Default
    // outside the working tree; CI passes an explicit output path.
    let output = match output {
        Some(path) => path.to_path_buf(),
        None => root.join("target").join("registry-catalog.json"),
    };
    if let Some(parent) = output
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    std::fs::write(&output, text).with_context(|| format!("writing {}", output.display()))?;
    println!(
        "wrote {} ({} manifests)",
        output.display(),
        bundle.manifests.len()
    );
    Ok(())
}

fn embedded_registry_text() -> Result<(String, usize)> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("workspace root")?;
    let registry = root.join("registry");
    let mut files = Vec::new();
    collect_manifests(&registry, &mut files)?;
    files.sort();
    if files.is_empty() {
        bail!("no manifests found under {}", registry.display());
    }

    let mut text = String::from(
        "// @generated by `cargo run -p xtask -- sync-embedded-registry`.\n\
         // Do not edit by hand.\n\n\
         /// Repository-relative path and JSON contents of every catalog manifest.\n\
         #[rustfmt::skip]\n\
         pub(crate) const MANIFESTS: &[(&str, &str)] = &[\n",
    );
    for file in &files {
        let relative = file
            .strip_prefix(&registry)
            .with_context(|| format!("{} is outside {}", file.display(), registry.display()))?
            .to_string_lossy()
            .replace('\\', "/");
        let contents =
            std::fs::read_to_string(file).with_context(|| format!("reading {}", file.display()))?;
        let manifest: olaya_core::RepoManifest = serde_json::from_str(&contents)
            .with_context(|| format!("parsing {}", file.display()))?;
        manifest
            .validate()
            .with_context(|| format!("validating {}", file.display()))?;
        writeln!(text, "    ({relative:?}, {contents:?}),")
            .context("building the embedded registry module")?;
    }
    text.push_str("];\n");
    Ok((text, files.len()))
}

fn sync_embedded_registry(check: bool) -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("workspace root")?;
    let path = root
        .join("crates")
        .join("olaya-cli")
        .join("src")
        .join("registry_seed.rs");
    let (text, count) = embedded_registry_text()?;
    if check {
        let existing = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        if existing != text {
            bail!(
                "{} is out of date; run `cargo run -p xtask -- sync-embedded-registry`",
                path.display()
            );
        }
        println!(
            "embedded registry is current ({} manifests, {})",
            count,
            path.display()
        );
        return Ok(());
    }
    std::fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
    println!("wrote {} ({} manifests)", path.display(), count);
    Ok(())
}

fn main() -> Result<()> {
    let args = std::env::args().skip(1).collect::<Vec<_>>();
    match args.first().map(String::as_str) {
        Some("check") if args.len() == 1 => check(),
        Some("sync-registry") => {
            let mut output = None;
            let mut index = 1;
            while index < args.len() {
                match args[index].as_str() {
                    "--output" => {
                        let value = args.get(index + 1).context("--output requires a path")?;
                        output = Some(PathBuf::from(value));
                        index += 2;
                    }
                    other => {
                        eprintln!("unknown sync-registry option {other}");
                        usage();
                    }
                }
            }
            sync_registry(output.as_deref())
        }
        Some("sync-embedded-registry") if args.len() == 1 => sync_embedded_registry(false),
        Some("check-embedded-registry") if args.len() == 1 => sync_embedded_registry(true),
        _ => usage(),
    }
}
